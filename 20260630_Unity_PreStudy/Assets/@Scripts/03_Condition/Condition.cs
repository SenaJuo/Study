using UnityEngine;

public class Condition : MonoBehaviour
{
    /*프로그램이라는 것은 다른말로 표현한다면  
     * 사람이 충분히 할 수 있는 행동을 컴퓨터에게 시킨다 정도로 말할 수 있음
     * 즉, 사람이 일을 하지 않도록 '자동화' 한다고 생각하면 됨
     * 
     * 사람은 어떤 행동을 할 때, 무의식적으로 다음과 같이 생각함
     * ~하면 ~하고 ~가 아니면 ~해야지
     * 이런 행동을 컴퓨터에게 시키기 위해서 조건문을 사용함
     * */

    private void Start()
    {
        //지갑에 10000원 있음
        //택시비가 11000원, 버스비는 2000원

        //지갑에 있는 돈과 교통수단의 비용을 비교해서
        //내가 탈 수 있는 교통수단을 정하고 싶음

        /*조건문(Condition)
        if라는 문법을 사용함
        if (조건)
        {
          실행 코드 
        }
        */
        Debug.Log("교통수단을 타는 프로그램 실행");
        //지갑에 10000원
        //택시 11000원
        /*   if(10000 < 110000)
           {
               Debug.Log("택시를 탈 수 있습니다.");
           }
        */
        //if문을 보면 소괄호 안에 있는 조건이
        //참이면, 중괄호 안에 있는 코드가 실행 됨
        //소괄호 안에 있는 조건이 거짓이면
        //중괄호 안에 있는 코드가 실행이 안됨

        int wallet = 10000;
        if (wallet >= 11000)
        {
            Debug.Log("택시를 탔음");
        }
        else if (wallet >= 2000)
        {
            Debug.Log("버스를 탔음");
        }
        //if-else if 문을 사용함
        //실제로 동시에 벌어지면 안되는 일들이 벌어져 버림
        //택시도 타면서 버스도 타는 이상한 상황이 되어버림
        //하나의 조건에 걸리면 다른 조건은 검사를 한다거나
        //실행하면 안되는 경우임

        //위에서부터 조건은 검사를 하는데
        //위에 조건이 걸려버리면(참이면)
        //아래 if문은 실행하지 않음
        //만약에, 택시를 탈 수 있으면 택시를 타는거고
        //그게 아니라, 만약에 버스를 탈 수 있으면 버스를 타라

        //if-else문
        //짝수 홀수 필터를 만들건데
        //어떤 수를 % 2를 했을때, 0이 나오면 짝수
        //그게아닌 모든 경우에 홀수라고 판명

        int someInt = 101;
        if (someInt % 2 == 0)
        {
            Debug.Log(someInt + "는 짝수 입니다.");
        }
        else
        {
            Debug.Log(someInt + "는 홀수 입니다");
        }

        /*
         * if-else에서
         * if-else if로 사용해도 결과상으로는 문제가 없음
         * 하지마, 2가지 밖에없는 경우에서 else if로
         * 조건을 명시하게 되면, 컴퓨터는 if문의 조건이
         * 거짓일 때, else if문의 조건도 검사하게 됨
         * A가 아니면 B인 경우에서는 A가 거짓이면 B는 무조건
         * 참이기 때문에 불필요하게 조건검사가 일어남
         * (지금은 하드웨어가 좋아져서 성능상 크게 문제는 없음)
         * (게임에서 프레임 단위로 복잡한 검사를 하게 되면, 문제가 생길 수 있음)
         */

        //만약에 A일떄, 어떤 행동을 수행을 하고
        //그게아니라, B일때, 어떤 행동을 수행하고 싶음
        //근데 위에 경우가 아닌 모든 경우에서 어떤 행동을 실행하고 싶음

        //if - else if - else


        //지갑에 10000원 있음
        //택시비가 11000원, 버스비는 2000원, 자전거 1000원
        //여기에 해당하지 않는 경우 걸어서 갈거임
        int wallet1 = 20000;
        if (wallet1 >= 11000)
        {
            Debug.Log("택시를 탔음");
        }
        else if (wallet1 >= 2000)
        {
            Debug.Log("버스를 탔음");
        }
        else if (wallet1 >= 1000)
        {
            Debug.Log("자전거를 탔음");
        }
        else
        {
            Debug.Log("걸어서 갔음");
        }

        //만약에, 택시를 탈 수 있을 때,
        //내 레벨이, 10 이상이면,
        //탈 수 있다를 출력해야하고
        //레벨이 10 미만이면 승차거부
        //1.&&
        //2.if 안에 if문을 쓸 수 있음

        bool rideTaxi = true;
        int level = 12;
        //&&
        if (rideTaxi && (level >= 10))
        {
            Debug.Log("택시를 탈 수 있습니다");
        }
        else
        {
            Debug.Log("승차거부");
        }
        //if 안에 if문을 쓸 수 있음
        //1. 택시를 탈 수 있는지 먼저 비교
        //2. 만약에 참이면, 중괄호 안에 코드가 실행이 됨
        //3. 실행되는 코드에 if문을 하나 더 넣음
        // - 레벨이 만족되는지에 대한 조건문

        if (rideTaxi == true)
        {
            if (level >= 10)
            {
                Debug.Log("택시를 탈 수 있습니다");
            }
            else
            {
                Debug.Log("승차거부");
            }
        }

        //switch case
        //순차적으로 증가하는 경우 if문 대신에
        //switch case를 쓰면 가독성이 올라감

        //if문으로 만들어봄
        //레벨이 오르면, 레벨에 해당하는 문구를 띄워줌
        //1렙 - 1렙 입니다.
        //2렙 - 2렙 입니다....

        int level1 = 2;
        if(level1 == 1)
        {
            Debug.Log("1레벨 입니다.");
        }
        else if(level1 == 2)
        {
            Debug.Log("2레벨 입니다.");
        }
        else if (level1 == 3)
        {
            Debug.Log("3레벨 입니다.");
        }
        else
        {
            Debug.Log("오류");
        }

        Debug.Log("---------------------------------------");

        switch (level1)
        {
            case 1:
                Debug.Log("레벨 1");
                break;
            case 2:
                Debug.Log("레벨 2");
                break;
            case 3:
                Debug.Log("레벨 3");
                break;
            default:
                Debug.Log("오류");
                break;
        }
    }
}