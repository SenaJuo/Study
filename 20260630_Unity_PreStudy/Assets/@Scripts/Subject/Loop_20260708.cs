             for(int b=0; b<=a; ++b) //첫번째 행 별 1개, 두번째 행 별 2개... 이렇게 행의 번호와 별의 숫자는 같아야 함
             {
                 Debug.Log("★");
             }
             Debug.Log("\n");
         }*/

        //---------풀이---------
        string star = "";

        for (int a = 0; a < 5; ++a)
        {
            for (int b = 0; b < a + 1; ++b)
            {
                star += "★";
            }
            Debug.Log(star);
            star = "";

        }
    }
