    /*
     * 2.지뢰찾기
     * 가로 6칸, 세로 5칸인 지뢰판이 있다고 가정함
     * 14번째, 19번째, 28번째 칸에 지뢰가 있다고 가정함
     * 지뢰가 총 3개이고, 3개의 지뢰를 모두 발견하면 게임 중단 //3개의 지뢰를 발견하면 break;
     * 매칸 확인할때마다 "XX칸 확인중.."을 출력 //
     * 지뢰를 찾을 때 마다, "XX칸에 있는 지뢰 확인 완료!" 를 출력 하면 됨
     * 
     * 큰 반복문이 세로 5칸
     * 그 안에 들어가는 반복문이 가로 6칸
     * 가로 6칸을 다 확인하면 그 다음줄로 넘어가서 다시 6칸을 확인
     */

    /*
     * 3. Star Pyramid
     * *
     * **
     * ***
     * ****
     * *****
     * 1.DebugLog 5개 안됨
     * 2.내가 100층짜리 피라미드를 만들고 싶으면 변수만 100으로 바꿨을때, 피라미드가 완성되면 됨
     * 2중 for문 사용
     * 
     */


    private void Start()
    {
        //1---------------------
        /* for (int i=1; i<10; ++i)
         {
             Debug.Log(i + "단-------"); //몇단
             for(int j =1; j<10; ++j) //어디까지 곱할건지
             {
                 int result = i * j; //계산값의 결과를 저장
                 Debug.Log(i + "X" + j + "="+result);
             }
         }
         */

        //2---------------------
        int step = 0; //step에 몇번째 칸을 탐색중인지
        int mine = 0; //발견한 지뢰 갯수

        for (int i = 0; i < 5; ++i) //세로
        {
            for (int j = 0; j < 6; ++j) //가로
            {
                ++step;
                Debug.Log(step + "번째 칸 탐색중");
                if (step == 14 || step == 19 || step == 28) //지뢰가 있다고 가정한 칸(14,19,28번째 칸)에 가면 지뢰 발견 출력
                {
                    Debug.Log(step + "번째 칸에 있는 지뢰 확인 완료");
                    ++mine;
                }

                if (mine == 3) //지뢰 3개를 다 발견하면 종료
                {
                    Debug.Log("모든 지뢰 발견");
                    break;
                }
            }
        }

        //3---------------------
        /* 
