using UnityEngine;

public class Loop_20260708 : MonoBehaviour
{
    //1. 구구단 만들기
    //1단부터 9단까지 구구단이 출력되도록 해보세요
    //출력예시 :
    /*
     *1단--------
     *1X1=1
     *1X2=2
     *...
     *1X9=9
     *9단까지
     *
     *A단
     *AXB=C
     *B가 9까지 돌고나면 A의 값이 올라가서 다시 B가 9까지
